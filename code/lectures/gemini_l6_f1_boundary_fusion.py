# ---- Check 3: Defect + Dirichlet boundary fusion matches Ghoshal-Zamolodchikov K_GZ(eta_D, lambda*theta_d) ----
def KD_diag(y, eta):
    return np.diag([y * np.exp(1j * eta) + np.exp(-1j * eta) / y, y * np.exp(-1j * eta) + np.exp(1j * eta) / y])


def K_fused_op(theta, theta_d_val, eta, N):
    T, _, W = sg_tmatrix(theta, lam, q, theta_d_val, N, s=0.0, scalar=False)
    Tm = sg_tmatrix(-theta, lam, q, theta_d_val, N, s=0.0, scalar=False)[0]
    Kb = KD_diag(np.exp(lam * theta), eta)
    return np.linalg.inv(Tm) @ np.kron(np.eye(W["dim"]), Kb) @ T, W


def K_gz_mat(y, eta, vt):
    e1 = -np.cos(eta - 1j * vt) / np.sin(np.pi * lam)
    e0 = -np.cos(eta + 1j * vt) / np.sin(np.pi * lam)
    kap = q - 1.0 / q
    return np.array([[kap * (e1 * y + e0 / y), y**2 - y ** (-2)], [y**2 - y ** (-2), kap * (e0 * y + e1 / y)]])


def sector_blocks_K(K, W, margin=2):
    ns = list(W["n"])
    N_max = max(ns)
    dW = W["dim"]
    out = []
    for n in ns:
        if abs(n) <= N_max - margin and abs(n + 1) <= N_max - margin:
            ix = [ns.index(n), dW + ns.index(n + 1)]
            out.append((n, K[np.ix_(ix, ix)]))
    return out


inv2 = lambda B: np.array([B[0, 0] / B[1, 1], (B[0, 1] * B[1, 0]) / (B[0, 0] * B[1, 1])])
dev_n_indep = 0.0
dev_gz_match = 0.0
dev_gauge_exact = 0.0

