def flip(d1, d2):
    P = np.zeros((d1 * d2, d1 * d2))
    for a in range(d1):
        for b in range(d2):
            P[b * d1 + a, a * d2 + b] = 1.0
    return P


def bdiag(A, B):
    Z = np.zeros((A.shape[0] + B.shape[0],) * 2, dtype=complex)
    Z[: A.shape[0], : A.shape[0]] = A
    Z[A.shape[0] :, A.shape[0] :] = B
    return Z


# ---- Check 1: Doubled bulk algebra U (x) U^cop vs U (x) U ----
def doubled_R_and_cop(y1, y2, use_cop=True):
    V1, V1p = sl2_spin(1, q, y1), sl2_spin(1, q, 1.0 / y1)
    V2, V2p = sl2_spin(1, q, y2), sl2_spin(1, q, 1.0 / y2)
    d = 2
    D = 4
    R0 = rcheck(V1, V2)[0]
    R1 = flip(d, d) @ rcheck(V2p, V1p)[0] @ flip(d, d)
    Rd = np.zeros((D * D, D * D), dtype=complex)
    for i in range(D):
        for j in range(D):
            ci, cj, li, lj = i // d, j // d, i % d, j % d
            if ci == cj:
                blk = R0 if ci == 0 else R1
                for k in range(d):
                    for l in range(d):
                        Rd[(ci * d + k) * D + ci * d + l, i * D + j] = blk[k * d + l, li * d + lj]
            else:
                Rd[j * D + i, i * D + j] = 1.0

    # Check intertwining on second factor (folded copy) generators
    worst = 0.0
    for j_node in (0, 1):
        for kd in ("e", "f", "k"):
            s1 = lambda V_pair, L: bdiag(np.eye(d) if L[0] == "k" else np.zeros((d, d)), V_pair[1][L])
            K1 = s1((V1, V1p), ("k", j_node))
            K2 = s1((V2, V2p), ("k", j_node))
            X1 = s1((V1, V1p), (kd, j_node))
            X2 = s1((V2, V2p), (kd, j_node))
            I4 = np.eye(D)
            if kd == "k":
                D12 = np.kron(K1, K2)
                D21 = np.kron(K2, K1)
            elif kd == "e":
                D12 = (np.kron(I4, X2) + np.kron(X1, K2)) if use_cop else (np.kron(X1, I4) + np.kron(K1, X2))
                D21 = (np.kron(I4, X1) + np.kron(X2, K1)) if use_cop else (np.kron(X2, I4) + np.kron(K2, X1))
            else:
                D12 = (
                    (np.kron(np.linalg.inv(K1), X2) + np.kron(X1, I4))
                    if use_cop
                    else (np.kron(X1, np.linalg.inv(K2)) + np.kron(I4, X2))
                )
                D21 = (
                    (np.kron(np.linalg.inv(K2), X1) + np.kron(X2, I4))
                    if use_cop
                    else (np.kron(X2, np.linalg.inv(K1)) + np.kron(I4, X1))
                )
            worst = max(worst, np.max(np.abs(Rd @ D12 - D21 @ Rd)) / np.max(np.abs(D12)))
    return worst


