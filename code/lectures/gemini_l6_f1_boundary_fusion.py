# ---- Check 2: Problem 6.2 (Second Borel module rho_tilde on W intertwines (1 (x) tau)Delta(U_q(b^+))) ----
def build_rho_tilde(yd, N, s_val=0.3):
    ns = np.arange(-N, N + 1)
    d = len(ns)
    a = 1j * yd * (q ** (-s_val)) / (q**2 - 1.0)
    b = 1j * yd * (q**s_val) / (q**2 - 1.0)
    g = {k: np.zeros((d, d), dtype=complex) for k in (("e", 1), ("e", 0), ("k", 1), ("k", 0))}
    for i, n in enumerate(ns):
        if i + 1 < d:
            g[("e", 1)][i + 1, i] = a * (q ** (-2 * n))
        if i - 1 >= 0:
            g[("e", 0)][i - 1, i] = b * (q ** (2 * n))
        if i + 2 < d:
            g[("k", 1)][i + 2, i] = q ** (-2 * n - 2 - s_val)
        if i - 2 >= 0:
            g[("k", 0)][i - 2, i] = q ** (2 * n - 2 + s_val)
    g.update(dim=d, n=ns)
    return g


