    np.max(np.abs((k1_rt @ e0_rt - (q ** (-2)) * (e0_rt @ k1_rt))[blk_rt])),
    np.max(np.abs((e1_rt @ e0_rt - e0_rt @ e1_rt)[blk_rt])),
