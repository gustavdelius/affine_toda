"""Classical affine Toda checks for Part III (chapters 9-11).

1. Lax pair (sec-lax-pair): zero curvature for a_2^(1) <=> field equation, with
   coefficients sqrt(n_j alpha_j^2/2).
2. Conserved current of sinh-Gordon built from d_+ (sec-conserved-charges); its charge
   has spin -3, checked on a plane wave of the linearized theory.
3. Masses: eigenvalues of m^2 sum n_j alpha_j alpha_j^T are proportional to the
   Perron-Frobenius vector (simply laced), sum rule sum m_a^2 = 2h m^2.
4. Cubic couplings |C_abc| proportional to the area of the mass triangle, and
   Dorey's fusing rule with gamma_a=(1-w^{-1})lambda_a, w=s_B s_W, for e7, e8, a_n.
5. Hirota (sec-hirota): bilinear equations, one- and two-soliton tau functions of
   a_n^(1) solve the time-dependent field equation; mass M_a = 2 h m_a / beta^2.
Also: the twisted a_2^(2) Lax pair; the sine-Gordon current and its charge on the kink; the
area rule and Dorey's rule in the charge basis (a2, a4, d4, e6); soliton position, folded
degrees, time-delay signs, fusion ranges and the neutral-breather band (sec-classical-solitons).
"""
import itertools
import numpy as np
import sympy as sp
import mpmath as mp


def report(name, ok):
    print(('PASS ' if ok else 'FAIL ') + name)


# ---------------------------------------------------------------- 1. Lax pair
xp, xm, lam, m, b = sp.symbols('xp xm lambda m beta', positive=True)
u1, u2 = sp.Function('u1')(xp, xm), sp.Function('u2')(xp, xm)
u = [u1, u2, -u1-u2]                       # phi as traceless diag(u1,u2,u3)
Phi = sp.diag(*u)
eij = lambda i, j: sp.Matrix(3, 3, lambda r, c: 1 if (r, c) == (i, j) else 0)
Ep = [eij(0, 1), eij(1, 2), eij(2, 0)]      # E_{alpha_1}, E_{alpha_2}, E_{alpha_0}
al = [lambda v: v[0]-v[1], lambda v: v[1]-v[2], lambda v: v[2]-v[0]]
coef = 1                                   # sqrt(n_j alpha_j^2/2) = 1 for a_n
Ap = b/2*sp.diff(Phi, xp) + m*lam*sum((coef*sp.exp(b*al[j](u)/2)*Ep[j] for j in range(3)), sp.zeros(3))
Am = -b/2*sp.diff(Phi, xm) - m/lam*sum((coef*sp.exp(b*al[j](u)/2)*Ep[j].T for j in range(3)), sp.zeros(3))
Fc = sp.diff(Am, xp) - sp.diff(Ap, xm) + Ap*Am - Am*Ap
# field equation d+d- phi = -(m^2/beta) sum_j n_j alpha_j e^{beta alpha_j.phi}, in diag components
alvec = [sp.Matrix([1, -1, 0]), sp.Matrix([0, 1, -1]), sp.Matrix([-1, 0, 1])]
rhs = -(m**2/b)*sum((alvec[j]*sp.exp(b*al[j](u)) for j in range(3)), sp.zeros(3, 1))
sub = {sp.Derivative(u1, xp, xm): rhs[0], sp.Derivative(u2, xp, xm): rhs[1]}
Fs = sp.simplify(Fc.subs(sub))
report('Lax pair zero curvature <=> a_2^(1) field equation', Fs == sp.zeros(3))

# Twisted a_2^(2): alpha_0 = -2 alpha_1, labels (1, 2), alpha_0^2 = 2, alpha_1^2 = 1/2, in 3x3 matrices.
# e_0 has weight alpha_0 = -2 alpha_1, which is not a root of the A_1 generated by e_1, f_1.
w1 = sp.Function('w1')(xp, xm); a1 = 1/sp.sqrt(2); alt = [-2*a1, a1]; nt = [1, 2]
Ht = a1*sp.diag(1, 0, -1); et = [eij(2, 0), sp.sqrt(2)*(eij(0, 1) + eij(1, 2))]
brk = lambda X, Y: X*Y - Y*X
alg_ok = all(brk(Ht, et[j]) == alt[j]*et[j] for j in range(2)) and all(
    sp.simplify(brk(et[i], et[j].T) - (2*Ht/alt[j] if i == j else sp.zeros(3))) == sp.zeros(3) for i in range(2) for j in range(2))
ct = [sp.sqrt(nt[j]*alt[j]**2/2) for j in range(2)]
Apt = b/2*sp.diff(w1, xp)*Ht + m*lam*sum((ct[j]*sp.exp(b*alt[j]*w1/2)*et[j] for j in range(2)), sp.zeros(3))
Amt = -b/2*sp.diff(w1, xm)*Ht - m/lam*sum((ct[j]*sp.exp(b*alt[j]*w1/2)*et[j].T for j in range(2)), sp.zeros(3))
Ft = sp.diff(Amt, xp) - sp.diff(Apt, xm) + brk(Apt, Amt)
eomt = -(m**2/b)*sum(nt[j]*alt[j]*sp.exp(b*alt[j]*w1) for j in range(2))
report('Lax pair zero curvature <=> a_2^(2) field equation (alpha_0 = -2 alpha_1, not a root of A_1)',
       alg_ok and sp.simplify(Ft.subs(sp.Derivative(w1, xp, xm), eomt)) == sp.zeros(3) and alt[0] not in (a1, -a1))

# ---------------------------------------------------------------- 2. sinh-Gordon spin 3
f = sp.Function('f')(xp, xm)
T4 = sp.diff(f, xp, 2)**2 + b**2/4*sp.diff(f, xp)**4
X2 = -m**2*sp.cosh(b*f)*sp.diff(f, xp)**2  # sec-factorization: d_- T4 = d_+ X2, density T4 - X2
expr = sp.diff(T4, xm) - sp.diff(X2, xp)
eom = -(m**2/b)*sp.sinh(b*f)           # d+d- f for V=(m^2/b^2)(cosh b f - 1), d+-=d_t+-d_x
expr = expr.subs(sp.Derivative(f, xp, xp, xm), sp.diff(eom, xp)).subs(sp.Derivative(f, xp, xm), eom)
report('sinh-Gordon: d_-T4 = d_+X2 with T4 = (d_+^2 f)^2+(b^2/4)(d_+ f)^4, X2 = -m^2 cosh(bf)(d_+ f)^2', sp.simplify(expr) == 0)

# The density T4 - X2 is conserved: d_t(T4 - X2) = d_x(T4 + X2), with d_t = (d_+ + d_-)/2, d_x = (d_+ - d_-)/2.
dens_flux = (sp.diff(T4 - X2, xp) + sp.diff(T4 - X2, xm)) - (sp.diff(T4 + X2, xp) - sp.diff(T4 + X2, xm))
dens_flux = dens_flux.subs(sp.Derivative(f, xp, xp, xm), sp.diff(eom, xp)).subs(sp.Derivative(f, xp, xm), eom)
report('sinh-Gordon: d_t(T4 - X2) = d_x(T4 + X2), so Q_{-3} = int (T4 - X2) dx is conserved', sp.simplify(dens_flux) == 0)

# Sign of the spin. A plane wave of rapidity th of the linearized theory has phase
# E t - p x = m e^{-th} xp + m e^{th} xm, so d_+ brings down m e^{-th}. Per particle, the
# quadratic part of T4 - X2 gives 2 m^3 e^{-3 th} (spin -3), its mirror d_+ <-> d_- 2 m^3 e^{3 th}.
amp, rap = sp.symbols('amp rap', positive=True)
wave = amp*sp.cos(m*sp.exp(-rap)*xp + m*sp.exp(rap)*xm)
avg = lambda g: sp.integrate(g.subs(xm, 0), (xp, 0, 2*sp.pi*sp.exp(rap)/m))*m*sp.exp(-rap)/(2*sp.pi)
d_t = lambda g: (sp.diff(g, xp) + sp.diff(g, xm))/2
d_x = lambda g: (sp.diff(g, xp) - sp.diff(g, xm))/2
density = avg((d_t(wave)**2 + d_x(wave)**2 + m**2*wave**2)/2)/(m*sp.cosh(rap))     # particles per length
q_m3 = avg(sp.diff(wave, xp, 2)**2 + m**2*sp.diff(wave, xp)**2)/density
q_p3 = avg(sp.diff(wave, xm, 2)**2 + m**2*sp.diff(wave, xm)**2)/density
report('plane wave: the d_+ density gives 2 m^3 e^{-3 theta} per particle (spin -3), the d_- density 2 m^3 e^{3 theta}',
       sp.simplify((q_m3 - 2*m**3*sp.exp(-3*rap)).rewrite(sp.exp)) == 0
       and sp.simplify((q_p3 - 2*m**3*sp.exp(3*rap)).rewrite(sp.exp)) == 0)

# Sine-Gordon by beta -> i beta: T4 = (d_+^2 f)^2 - (b^2/4)(d_+ f)^4, X2 = -m^2 cos(bf)(d_+ f)^2, with
# d+d- f = -(m^2/b) sin(bf), V = (m^2/b^2)(1 - cos bf) (m, b = m_0, beta_SG). On the kink of rapidity th,
# f = (4/b) arctan exp(m(x cosh th - t sinh th)), Q_{-3} = int (T4 - X2) dx = -16 m^3 e^{-3 th}/(3 b^2).
T4s = sp.diff(f, xp, 2)**2 - b**2/4*sp.diff(f, xp)**4
X2s = -m**2*sp.cos(b*f)*sp.diff(f, xp)**2
eoms = -(m**2/b)*sp.sin(b*f)
exs = (sp.diff(T4s, xm) - sp.diff(X2s, xp)).subs(sp.Derivative(f, xp, xp, xm), sp.diff(eoms, xp)).subs(sp.Derivative(f, xp, xm), eoms)


def kink_q3(th, mm=mp.mpf(1), bb=mp.mpf('0.8')):
    def dens(x):
        z = mm*x*mp.cosh(th); k = mm*mp.e**(-th)               # d_+ z = m e^{-th}
        p1 = k*2/bb/mp.cosh(z); p2 = -k**2*2/bb*mp.tanh(z)/mp.cosh(z)
        return p2**2 - bb**2/4*p1**4 + mm**2*mp.cos(4*mp.atan(mp.e**z))*p1**2
    return mp.quad(dens, [-mp.inf, 0, mp.inf])


kq = max(abs(kink_q3(th) + 16/(3*mp.mpf('0.8')**2)*mp.e**(-3*th)) for th in (mp.mpf(0), mp.mpf('0.6'), mp.mpf('-0.45')))
report(f'sine-Gordon (beta -> i beta): d_-T4 = d_+X2; on the kink Q_-3 = -16 m0^3 e^(-3 theta)/(3 beta_SG^2)  [res {float(kq):.1e}]',
       sp.simplify(exs) == 0 and kq < 1e-12)

# ---------------------------------------------------------------- root data
def cartan(typ, n):
    C = 2*np.eye(n)
    if typ == 'a':
        for i in range(n-1): C[i, i+1] = C[i+1, i] = -1
    elif typ == 'd':
        for i in range(n-2): C[i, i+1] = C[i+1, i] = -1
        C[n-3, n-1] = C[n-1, n-3] = -1
    elif typ == 'e':
        for i in range(n-2): C[i, i+1] = C[i+1, i] = -1   # chain 1..n-1, node n attached to node 3
        C[2, n-1] = C[n-1, 2] = -1
    return C


def simple_roots(C):
    L = np.linalg.cholesky(C)                 # rows: simple roots with alpha_i.alpha_j = C_ij
    return L


def all_roots(al):
    r = len(al); roots = {tuple(np.round(a, 12)) for a in al}; frontier = list(al)
    while frontier:
        new = []
        for v in frontier:
            for a in al:
                for s in (1, -1):
                    w_ = v - (v @ a)*a if s == 1 else v
                    t = tuple(np.round(w_, 12))
                    if t not in roots:
                        roots.add(t); new.append(w_)
        frontier = new
    roots |= {tuple(-np.array(t)) for t in roots}
    return [np.array(t) for t in roots]


def data(typ, n):
    C = cartan(typ, n); al = simple_roots(C)
    roots = all_roots(list(al))
    theta = max(roots, key=lambda v: np.linalg.solve(al.T, v).sum())
    marks = np.round(np.linalg.solve(al.T, theta)).astype(int)
    h = 1 + marks.sum()
    a0 = -theta
    A = np.vstack([a0, al]); nj = np.concatenate([[1], marks])
    M2 = sum(nj[j]*np.outer(A[j], A[j]) for j in range(n+1))
    return C, al, roots, h, A, nj, M2


