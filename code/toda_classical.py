# Degenerate masses: charge basis = joint eigenvectors of M^2 and the centre of the affine diagram,
# acting by the linear map L with L alpha_j = alpha_perm(j). Bilinear couplings (no conjugation).
def centre_map(A, perm):
    L = np.linalg.solve(A[1:], np.array([A[perm[j]] for j in range(1, len(A))])).T
    assert np.allclose(L @ A[0], A[perm[0]]) and np.allclose(L.T @ L, np.eye(len(L)))
    return L


def coxeter_mass_triples(typ, n):
    C, al, h, A, nj, M2, orbits, partition = dorey(typ, n)
    ev, U = np.linalg.eig(np.array([o[1] for o in orbits]).T @ np.linalg.inv(np.array([o[0] for o in orbits]).T))
    u_ = U[:, np.argmin(abs(ev - np.exp(2j*np.pi/h)))]
    ms = np.array([abs(np.conj(u_) @ o[0]) for o in orbits]); ms /= ms.min()
    sets = [{tuple(np.round(v, 6)) for v in o} for o in orbits]
    return sorted(tuple(sorted(np.round(ms[list(t)], 6))) for t in itertools.combinations_with_replacement(range(n), 3)
                  if any(tuple(np.round(-x-y, 6)) in sets[t[2]] for x in orbits[t[0]] for y in orbits[t[1]]))


def area2(ma, mb, mc):
    s_ = (ma+mb+mc)/2
    return s_*(s_-ma)*(s_-mb)*(s_-mc)


