import numpy as np

# Explicit construction of V_1 \otimes V_1 at q = exp(i * pi / p) for p = 4.
p = 4
q = np.exp(1j * np.pi / p)

def qnum(n, q):
    return (q**n - q**(-n)) / (q - 1.0/q)

print(f"p = {p}, q = {q}")
for n in range(1, 2*p + 1):
    print(f"[{n}]_q = {qnum(n, q):.4f}")

# Check [5]_q and [3]_q:
print(f"[5]_q = {qnum(5, q):.4f}")
print(f"[3]_q = {qnum(3, q):.4f}")
print(f"[5]_q + [3]_q = {qnum(5, q) + qnum(3, q):.4e}")

# Build spin 1 generators:
# Basis v_0, v_1, v_2
E1 = np.zeros((3, 3), complex)
F1 = np.zeros((3, 3), complex)
K1 = np.zeros((3, 3), complex)

# From eq-spin-j with j=1:
# K v_k = q^(2 - 2k) v_k
# F v_k = v_{k+1}
# E v_k = [k]_q [2j+1-k]_q v_{k-1} = [k]_q [3-k]_q v_{k-1}
K1[0, 0] = q**2
K1[1, 1] = 1.0
K1[2, 2] = q**(-2)

F1[1, 0] = 1.0
F1[2, 1] = 1.0

E1[0, 1] = qnum(1, q) * qnum(2, q) # [1][2]
E1[1, 2] = qnum(2, q) * qnum(1, q) # [2][1]

# Check sl2 relations on spin 1:
comm = E1 @ F1 - F1 @ E1
target = (K1 - np.linalg.inv(K1)) / (q - 1.0/q)
print(f"Spin 1 relation err: {np.max(np.abs(comm - target)):.2e}")

# Build coproduct on V_1 \otimes V_1:
# Delta(K) = K \otimes K
# Delta(E) = E \otimes K + 1 \otimes E
# Delta(F) = F \otimes 1 + K^-1 \otimes F
Delta_K = np.kron(K1, K1)
Delta_E = np.kron(E1, K1) + np.kron(np.eye(3), E1)
Delta_F = np.kron(F1, np.eye(3)) + np.kron(np.linalg.inv(K1), F1)

# Verify relations for Delta:
comm_D = Delta_E @ Delta_F - Delta_F @ Delta_E
target_D = (Delta_K - np.linalg.inv(Delta_K)) / (q - 1.0/q)
print(f"Delta sl2 relation err: {np.max(np.abs(comm_D - target_D)):.2e}")

# Find highest weight vectors: ker(Delta_E)
u, s, vh = np.linalg.svd(Delta_E)
hw_indices = np.where(s < 1e-10)[0]
num_hw = len(hw_indices) + (9 - len(s))
print(f"Number of highest weight vectors (dim ker Delta_E): {num_hw}")

# For each null vector of Delta_E, find its K eigenvalue:
null_vectors = vh[len(s)-num_hw:, :]
for i, v in enumerate(null_vectors):
    Kv = Delta_K @ v
    ratio = Kv[np.argmax(np.abs(v))] / v[np.argmax(np.abs(v))]
    print(f"  HW vector {i}: Delta_K eigenvalue = {ratio:.4f}")

# Look at the module generated by the highest weight vector of weight q^4 = -1 (spin 2):
# Top vector is v_0 \otimes v_0 (weight q^4 = -1)
v_top = np.zeros(9, complex)
v_top[0] = 1.0
descendants = [v_top]
cur = v_top
for step in range(1, 9):
    cur = Delta_F @ cur
    norm = np.linalg.norm(cur)
    if norm > 1e-10:
        descendants.append(cur)
        print(f"  Step {step}: descendant norm = {norm:.4f}")
    else:
        print(f"  Step {step}: descendant is ZERO (annihilated by F^4?)")
        break

subspace = np.column_stack(descendants)
q, r = np.linalg.qr(subspace)
rank = np.sum(np.abs(np.diag(r)) > 1e-8)
print(f"Dimension of submodule generated by top vector: {rank}")
