"""Referee check of prp-no-dirichlet (ch. 30), independent of code.

For a Dirichlet wall phi(0)=phi_0 the boundary value of every exponential is a
constant w_j, and d_x phi(0) is free.  Sklyanin's compatibility condition

    K a_t(lam) + sigma(a_t(1/lam)) K = 0

must then hold for every d_x phi(0).  We build the Lax operator in several
representations NOT used by the book's script (b_2 and c_3 vector, g_2 7-dim,
a_2 symmetric square, d_4 adjoint) and compute the dimension of the space of
solutions K, for

  * sigma = antipode, sigma = transposition (linear, real or imaginary coupling);
  * sigma = Hermitian conjugation and sigma = -(complex conjugation)
    (antilinear, imaginary coupling, complex d_x phi).

Expected: nullity 0 for every algebra except a_1 (sinh-/sine-Gordon), where a
solution exists.
"""
import itertools
import numpy as np

rng = np.random.default_rng(11)


def E(n, i, j):
    m = np.zeros((n, n), dtype=complex)
    m[i, j] = 1
    return m


def comm(a, b):
    return a @ b - b @ a


# ---------- representations: lists of Chevalley E_j (j>=1); F_j = E_j^T ----------
def a_vector(n):
    N = n + 1
    return [E(N, i, i + 1) for i in range(n)]


def b2_vector():
    # so(5) in the basis (e1, e2, e0, -e2, -e1), metric antidiagonal
    N = 5
    # alpha_1 = e1-e2 (long), alpha_2 = e2 (short)
    E1 = E(N, 0, 1) - E(N, 3, 4)
    E2 = np.sqrt(2) * (E(N, 1, 2) - E(N, 2, 3))
    return [E1, E2]


def c3_vector():
    # sp(6), basis (e1,e2,e3,-e3,-e2,-e1)
    N = 6
    E1 = E(N, 0, 1) - E(N, 4, 5)
    E2 = E(N, 1, 2) - E(N, 3, 4)
    E3 = E(N, 2, 3)
    return [E1, E2, E3]


def d4_vector():
    # so(8), basis (e1..e4, -e4..-e1)
    N = 8
    idx = {('+', k): k for k in range(4)}
    idx.update({('-', k): 7 - k for k in range(4)})

    def root(i, j, si, sj):
        # generator for root si*e_i + sj*e_j acting on vectors
        # raising e_{i} <- e_{j} pattern for e_i - e_j: E_{i,j} - E_{-j,-i}
        pass

    E1 = E(N, 0, 1) - E(N, 6, 7)
    E2 = E(N, 1, 2) - E(N, 5, 6)
    E3 = E(N, 2, 3) - E(N, 4, 5)
    E4 = E(N, 2, 4) - E(N, 3, 5)   # e3+e4
    return [E1, E2, E3, E4]


def g2_7dim(signs=(1, 1, 1, 1)):
    N = 7
    a, b, c, d = signs
    E1 = a * E(N, 0, 1) + b * np.sqrt(2) * E(N, 2, 3) + c * np.sqrt(2) * E(N, 3, 4) + d * E(N, 5, 6)
    E2 = E(N, 1, 2) + E(N, 4, 5)
    return [E1, E2]


def lie_closure_dim(gens):
    """dimension of the Lie algebra generated by gens (as real/complex span)"""
    basis = []

    def add(m):
        v = m.reshape(-1)
        if not basis:
            if np.linalg.norm(v) > 1e-9:
                basis.append(v)
                return True
            return False
        A = np.array(basis).T
        x, *_ = np.linalg.lstsq(A, v, rcond=None)
        if np.linalg.norm(A @ x - v) > 1e-8:
            basis.append(v)
            return True
        return False

    mats = []
    for g in gens:
        if add(g):
            mats.append(g)
    i = 0
    while i < len(mats):
        for j in range(len(mats)):
            c = comm(mats[i], mats[j])
            if add(c):
                mats.append(c)
        i += 1
    return len(mats), mats


def tensor_sym2(gens):
    """symmetric square of a representation (as matrices on Sym^2)"""
    N = gens[0].shape[0]
    pairs = [(i, j) for i in range(N) for j in range(i, N)]
    # basis vectors of Sym^2 in V⊗V
    B = []
    for (i, j) in pairs:
        v = np.zeros(N * N, dtype=complex)
        v[i * N + j] += 1
        v[j * N + i] += 1
        B.append(v / np.linalg.norm(v))
    B = np.array(B).T
    out = []
    for g in gens:
        G = np.kron(g, np.eye(N)) + np.kron(np.eye(N), g)
        out.append(B.conj().T @ G @ B)
    return out


def adjoint(gens):
    dim, mats = lie_closure_dim(gens + [g.T for g in gens])
    Bm = np.array([m.reshape(-1) for m in mats]).T

    def ad(X):
        cols = []
        for m in mats:
            c = comm(X, m).reshape(-1)
            x, *_ = np.linalg.lstsq(Bm, c, rcond=None)
            cols.append(x)
        return np.array(cols).T
    # orthonormalize so that transposition is meaningful: use Killing-type inner
    # product only for H diagonal; we simply return ad matrices; transposition
    # is then replaced by the contragredient below (rho' = rho*) which is what
    # the proof uses.
    return [ad(g) for g in gens], [ad(g.T) for g in gens]


def minus_theta(Es, Fs):
    """E_{-theta}: a nonzero nested commutator of maximal length of the F_j"""
    best = None
    frontier = [(F, 1) for F in Fs]
    level = {1: Fs[:]}
    cur = [F for F in Fs]
    depth = 1
    while True:
        nxt = []
        for X in cur:
            for F in Fs:
                Y = comm(F, X)
                if np.linalg.norm(Y) > 1e-9:
                    # keep one representative per direction
                    nxt.append(Y)
        if not nxt:
            break
        # dedupe by direction
        ded = []
        for Y in nxt:
            y = Y.reshape(-1) / np.linalg.norm(Y)
            if not any(abs(abs(np.vdot(y, z.reshape(-1) / np.linalg.norm(z))) - 1) < 1e-9 for z in ded):
                ded.append(Y)
        cur = ded
        depth += 1
    assert len(cur) == 1, len(cur)
    return cur[0], depth   # depth = height of theta = h-1


def solve_nullity(eqs, N):
    """eqs: list of functions K -> matrix, linear in K.  return nullity."""
    cols = []
    for k in range(N * N):
        K = np.zeros(N * N, dtype=complex)
        K[k] = 1
        K = K.reshape(N, N)
        cols.append(np.concatenate([f(K).reshape(-1) for f in eqs]))
    A = np.array(cols).T
    s = np.linalg.svd(A, compute_uv=False)
    tol = 1e-9 * max(1, s[0])
    return int(np.sum(s < tol)) + max(0, N * N - len(s)), s[-1]


def check(name, Es, Fs=None, contragredient=None, coupling='real'):
    if Fs is None:
        Fs = [e.T.copy() for e in Es]
    N = Es[0].shape[0]
    Em, depth = minus_theta(Es, Fs)
    # E_{alpha_0} = E_{-theta}, E_{-alpha_0} = E_theta (transpose if available)
    Ep, _ = minus_theta(Fs, Es)   # E_theta: maximal nested commutator of the E_j
    EE = [Em] + list(Es)
    FF = [Ep] + list(Fs)
    Hs = [comm(e, f) for e, f in zip(Es, Fs)]
    lam = 0.7 * np.exp(0.37j)
    w = rng.normal(size=len(EE)) + 1j * rng.normal(size=len(EE))

    def step(l):
        return sum(wj * (l * e - f / l) for wj, e, f in zip(w, EE, FF))

    res = {}
    # linear sigmas
    T = lambda X: X.T
    for sname, sig in [('antipode', lambda X: -X), ('transpose', T)]:
        eqs = [lambda K, H=H: K @ H + sig(H) @ K for H in Hs]
        eqs.append(lambda K: K @ step(lam) + sig(step(1 / lam)) @ K)
        res[sname] = solve_nullity(eqs, N)[0]
    # antilinear sigmas at imaginary coupling: Cartan coefficient i*beta/2*(u+iv)
    for sname, sig in [('hermitian', lambda X: X.conj().T), ('-conj', lambda X: -X.conj())]:
        eqs = []
        for H in Hs:
            for coef in (1j, -1.0):     # u-part (i*u.H) and v-part (i*i*v.H)
                eqs.append(lambda K, H=H, c=coef: K @ (c * H) + sig(c * H) @ K)
        eqs.append(lambda K: K @ step(lam) + sig(step(1 / lam)) @ K)
        res[sname] = solve_nullity(eqs, N)[0]
    print(f"{name:28s} dim={N:3d} ht(theta)={depth}  nullity:", res)
    return res


