def fock_hom():
    q=s.Rational(2); ys=[s.Rational(3,2),s.Rational(5,4)]; yd=s.Rational(7,6)
    mu=s.I/(q-1/q)
    def states(l):
        return [ab for ab in itertools.product((1,-1),repeat=2) if l-sum(ab)//2>=0]
    def gen(l,node):
        direction=1 if node==1 else -1
        src=states(l);dst=states(l+direction);M=s.zeros(len(dst),len(src))
        for col,ab in enumerate(src):
            n=l-sum(ab)//2
            for i in range(3):
                out=list(ab)
                if i<2:
                    if ab[i]!=-direction:continue
                    out[i]=direction
                    amp=ys[i]*q**(direction*sum(ab[:i]))
                else:
                    if direction==-1 and n==0:continue
                    amp=mu*yd*q**(direction*sum(ab))
                    if direction==-1:amp*=1-q**(2*n)
                M[dst.index(tuple(out)),col]+=amp
        return M
    A=lambda l:gen(l,1);B=lambda l:gen(l,0)
    low=A(-1);loop0=B(1)*A(0)
    reach0=s.Matrix.hstack(low,loop0*low,loop0**2*low)
    seed1=A(0)*reach0;loop1=B(2)*A(1)
    reach1=s.Matrix.hstack(seed1,loop1*seed1)
    print('Fock+ lowest-weight cyclicity: block0 rank',reach0.rank(),
          'block1 rank',reach1.rank(),'det A1',s.factor(A(1).det()))
    assert reach0.rank()==3 and reach1.rank()==4 and A(1).det()!=0
    # For all l>=1, A(l) is triangular plus a nonzero diagonal W shift.
    # Therefore all blocks are generated by the one-dimensional lowest block.
    # An endomorphism preserves that block and hence is a scalar everywhere.


def weyl_plus():
    q=np.exp(.71j);x=.83;off=.3
    # Input column |a,n>; L+ = diag(q^(h/2),q^(-h/2)) (1+i x shifts).
    # The charge block is |+,n>,|-,n+1>.
    def inverse_block(n):
        L=np.array([[q**(n+off/2),1j*x*q**(n+off/2)],
                    [1j*x*q**(-n-1-off/2),q**(-n-1-off/2)]])
        return np.linalg.inv(L)
    L0=inverse_block(0);L1=inverse_block(1)
    err=np.max(np.abs(L1-L0@np.diag([1/q,q])))
    print('Weyl+ inverse n-shift equals column factor q^(-a):',err)
    print('N=1 W+ diagonal <1|M|1>/<0|M|0>:',L1[0,0]/L0[0,0],
          'expected q^-1:',1/q,'book unqualified q:',q)
    assert err<1e-12


def level_zero_windows():
    q=s.Rational(2); f=s.Rational(3,5);y=s.Rational(7,6)
    for c in (s.Integer(1),s.Integer(-1),s.Integer(4),s.Rational(1,4)):
        variables=s.symbols('v:20');L={n:s.Matrix(2,2,variables[4*(n+2):4*(n+3)]) for n in range(-2,3)}
        equations=[]
        for n in range(-1,2):
            H=s.Matrix([[f,0],[q**(-2*n)/y,f]])
            Hp=s.Matrix([[f/q,0],[1/y,f*q]])
            G=s.Matrix([[f,q**(2*n+2)/(y*c)],[0,f]])
            Gp=s.Matrix([[f*q,1/y],[0,f/q]])
            equations+=list(L[n-1]*H-Hp*L[n])+list(L[n+1]*G-Gp*L[n])
        M,_=s.linear_eq_to_matrix(equations,variables)
        print('level c=',c,'finite necessary-equation nullity',len(variables)-M.rank())


