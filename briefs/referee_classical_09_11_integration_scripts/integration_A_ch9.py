report('a_2^(2): eq-lax-pair with c_j = sqrt(n_j alpha_j^2/2) has zero curvature <=> field equation',
       sp.simplify(Fc.subs(sp.Derivative(u, xp, xm), rhs)) == sp.zeros(3))
# e_1, f_1 generate an sl(2) whose roots are +-alpha_1; e_0 has weight alpha_0 = -2 alpha_1, not a root of it
