# ---- item 1: sine-Gordon current by beta -> i beta, and Q_{-3} on the moving kink
xp, xm, m, b = sp.symbols('xp xm m beta', positive=True)
f = sp.Function('f')(xp, xm)
T4 = sp.diff(f, xp, 2)**2 - b**2/4*sp.diff(f, xp)**4          # beta -> i beta in T4
X2 = -m**2*sp.cos(b*f)*sp.diff(f, xp)**2                      # cosh(beta f) -> cos(beta f)
eom = -(m**2/b)*sp.sin(b*f)          # V = (m^2/b^2)(1 - cos b f): d+d- f = -V'(f), d_pm = d_t pm d_x
e = sp.diff(T4, xm) - sp.diff(X2, xp)
e = e.subs(sp.Derivative(f, xp, xp, xm), sp.diff(eom, xp)).subs(sp.Derivative(f, xp, xm), eom)
report('sine-Gordon: d_-T4 = d_+X2 with T4=(d+^2f)^2-(b^2/4)(d+f)^4, X2=-m^2 cos(bf)(d+f)^2', sp.simplify(e) == 0)
# the sinh-Gordon potential of the example is (m0^2/bSG^2)(cosh bSG f - 1) of sec-sg-dictionary:
# with b -> i b it becomes (m^2/b^2)(1 - cos b f) = eq-sg-lagrangian's potential with m=m0, b=bSG
V = m**2/b**2*(sp.cosh(b*f) - 1)
report('beta -> i beta maps (m^2/b^2)(cosh bf - 1) to (m^2/b^2)(1 - cos bf)',
       sp.simplify(V.subs(b, sp.I*b) - m**2/b**2*(1 - sp.cos(b*f))) == 0)

mp.mp.dps = 20
def Qm3(th, mm=mp.mpf(1), bb=mp.mpf('0.8')):
    # kink phi = (4/b) arctan exp(m(x cosh th - t sinh th)) at t = 0; d_+ = d_t + d_x
    def dens(x):
        z = mm*x*mp.cosh(th)
        phi = 4/bb*mp.atan(mp.e**z)
        g1 = 2/bb/mp.cosh(z)                       # d phi/dz
        g2 = -2/bb*mp.tanh(z)/mp.cosh(z)           # d^2 phi/dz^2
        k = mm*(mp.cosh(th) - mp.sinh(th))         # d_+ z = m e^{-th}
        p1, p2 = k*g1, k**2*g2
        T = p2**2 - bb**2/4*p1**4; X = -mm**2*mp.cos(bb*phi)*p1**2
        return T - X
    return mp.quad(dens, [-mp.inf, 0, mp.inf])
ok = all(abs(Qm3(th) - (-16*mp.mpf(1)/(3*mp.mpf('0.8')**2)*mp.e**(-3*th))) < 1e-15 for th in (0, mp.mpf('0.6'), mp.mpf('-0.45')))
report('kink: Q_{-3} = int (T4 - X2) dx = -16 m0^3 e^{-3 theta}/(3 beta_SG^2) at theta = 0, 0.6, -0.45', ok)

# ---- item 5: a_2^(2) Lax pair, alpha_0 = -2 alpha_1, labels (1, 2), alpha_0^2 = 2, alpha_1^2 = 1/2
a1 = 1/sp.sqrt(2); al = [-2*a1, a1]; nj = [1, 2]
E = lambda i, j: sp.Matrix(3, 3, lambda r, c: 1 if (r, c) == (i, j) else 0)
H = a1*sp.diag(1, 0, -1)
ep = [E(2, 0), sp.sqrt(2)*(E(0, 1) + E(1, 2))]; fm = [x.T for x in ep]
br = lambda X, Y: X*Y - Y*X
ok = all(br(H, ep[j]) == al[j]*ep[j] for j in range(2))
ok &= all(sp.simplify(br(ep[i], fm[j]) - (2*al[j]/al[j]**2*H if i == j else sp.zeros(3))) == sp.zeros(3) for i in range(2) for j in range(2))
