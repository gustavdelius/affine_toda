# ---- item 7: spins of a_4^(2) from the centralizer of E_1 in the twisted loop algebra
N = 5
def Emat(i, j):
    M = np.zeros((N, N)); M[i, j] = 1; return M
Lam = {0: sum(Emat(i, i+1) for i in range(N-1)), 1: Emat(N-1, 0)}     # E_1 = Lambda, coefficients of z^0, z^1
def sigma_ok(K):
    # sigma(X)(z) = -K X(-z)^T K^{-1}; must fix Lambda
    return all(np.allclose(-K @ (Lam[p]*(-1)**p).T @ np.linalg.inv(K), Lam[p]) for p in Lam)
K = None
for signs in itertools.product([1, -1], repeat=N):
    Kt = np.zeros((N, N))
    for i in range(N): Kt[i, N-1-i] = signs[i]
    if sigma_ok(Kt): K = Kt; break
dims = {}
for s in range(1, 2*N+1):
    basis = []                                         # (i, j, p): E_ij z^p with principal degree j - i + N p = s
    for i in range(N):
        for j in range(N):
            if (s - (j - i)) % N == 0: basis.append((i, j, (s - (j - i))//N))
    rows = []
    def vec_of(coeffs):                                # matrix-valued Laurent poly as dict p -> matrix, flattened
        return coeffs
    eqs = []
    for idx, (i, j, p) in enumerate(basis):
        X = {p: Emat(i, j)}
        comm = {}
        for q_, Lq in Lam.items():
            comm[p+q_] = comm.get(p+q_, 0) + Lq @ X[p] - X[p] @ Lq
        sig = {p: -K @ (Emat(i, j)*(-1)**p).T @ np.linalg.inv(K)}
        eqs.append((comm, sig, X))
    keys = sorted({k for c_, s_, X in eqs for k in list(c_) + list(s_)})
    def flat(dct): return np.concatenate([np.ravel(dct.get(k, np.zeros((N, N)))) for k in keys])
    Mc = np.array([flat(c_) for c_, s_, X in eqs]).T
    Ms = np.array([flat(s_) - flat(X) for c_, s_, X in eqs]).T
    tr = np.array([[1.0 if (i == j) else 0.0 for (i, j, p) in basis]])   # traceless (sl(5)); only bites when s = 0 mod 5
    Mall = np.vstack([Mc, Ms, tr])
    sv = np.linalg.svd(Mall, compute_uv=False)
    dims[s] = len(basis) - int(np.sum(sv > 1e-9))
expected = {s: (1 if (s % 2 == 1 and s % 5 != 0) else 0) for s in dims}
print('   a_4^(2) centralizer dimensions by principal degree 1..10:', dims)
report('a_4^(2): the centralizer of E_1 has degrees 1,3,7,9 mod 10 (odd, not divisible by 5), as in ch. 9', K is not None and dims == expected)
