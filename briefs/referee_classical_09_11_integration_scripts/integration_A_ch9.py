Ap = b/2*sp.diff(u, xp)*H + m*lam*sum((c[j]*sp.exp(b*al[j]*u/2)*ep[j] for j in range(2)), sp.zeros(3))
Am = -b/2*sp.diff(u, xm)*H - m/lam*sum((c[j]*sp.exp(b*al[j]*u/2)*fm[j] for j in range(2)), sp.zeros(3))
Fc = sp.diff(Am, xp) - sp.diff(Ap, xm) + br(Ap, Am)
