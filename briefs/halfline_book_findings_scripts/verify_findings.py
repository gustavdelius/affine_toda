# ------------------------------------------------------------------ B1
# a_n vector rep, principal gradation (book ch. 33): V(y): e_j = y E_{j,j+1}, f_j = F/y, k_j = q^{H_j};
# Vbar(y): e_j = y F_j, f_j = E_j / y, k_j = q^{-H_j}.  b_j = e_j + q^-1 f_j k_j + eps_j k_j.
def an_rep(n, q, y, bar=False):
    N = n + 1
    out = {}
    for j in range(N):
        a, b = (j - 1) % N, j % N
        E = np.zeros((N, N), complex); E[a, b] = 1
        H = np.zeros((N, N), complex); H[a, a] += 1; H[b, b] -= 1
        if bar:
            e, f, k = y * E.T, E / y, np.diag(q ** (-np.diag(H)))
        else:
            e, f, k = y * E, E.T / y, np.diag(q ** np.diag(H))
        out[j] = (e, f, k)
    return out


def algebra_span(gens, dim):
    """Basis (as flattened vectors) of the unital matrix algebra generated by gens."""
    basis = [np.eye(dim).ravel()]
    mats = [np.eye(dim)]
    frontier = [np.eye(dim)]
    def add(M):
        B = np.array(basis)
        v = M.ravel()
        coef, *_ = np.linalg.lstsq(B.T, v, rcond=None)
        r = v - B.T @ coef
        if np.linalg.norm(r) > 1e-9 * max(1, np.linalg.norm(v)):
            basis.append(v); mats.append(M); return True
        return False
    while frontier:
        new = []
        for M in frontier:
            for g in gens:
                P = g @ M
                if add(P):
                    new.append(P)
        frontier = new
    return np.array(basis)


def in_span(B, M):
    v = M.ravel()
    coef, *_ = np.linalg.lstsq(B.T, v, rcond=None)
    return np.linalg.norm(v - B.T @ coef) / np.linalg.norm(v)


omega = np.sqrt(2) + np.e / 10
q = -np.exp(-1j * np.pi * omega)
y = 0.83 * np.exp(0.37j)
eps_star = 1 / np.sqrt((1 - q) * (1 - 1 / q))
rng = np.random.default_rng(7)
for n in (2, 3):
    N = n + 1
    for label, eps in (('generic', rng.normal(size=N) + 1j * rng.normal(size=N)),
                       ('s=+1', np.full(N, eps_star))):
        V, Vb = an_rep(n, q, y), an_rep(n, q, 1 / y, bar=True)
        def rho(j, which):
            e, f, k = which(j)
            return e, f, k
        gens = []
        blocks = {}
        for j in range(N):
            m = []
            for R in (V, Vb):
                e, f, k = R[j]
                m.append(e + f @ k / q + eps[j] * k)
            g = np.block([[m[0], np.zeros((N, N))], [np.zeros((N, N)), m[1]]])
            gens.append(g)
        A = algebra_span(gens, 2 * N)
        def rho_el(fn):
            return np.block([[fn(V), np.zeros((N, N))], [np.zeros((N, N)), fn(Vb)]])
        i, j = 1, 2              # adjacent nodes
        kap = rho_el(lambda R: R[i][2] @ R[i][2] @ R[j][2])
        kapinv = np.linalg.inv(kap)
        ei = rho_el(lambda R: R[i][0])
        fiki = rho_el(lambda R: R[i][1] @ R[i][2])
        k2 = [rho_el(lambda R, m=m: R[m][2] @ R[m][2]) for m in range(N)]
        res = [in_span(A, X) for X in [kap, kapinv, ei, fiki] + k2]
        if label == 'generic':
            report(f'B1 a_{n}, generic eps: rho(B) on V(y)+Vbar(1/y) has dim {A.shape[0]}; it contains rho(kappa), '
                   f'rho(kappa^-1), e_i, f_i k_i and all k_m^2 [max res {max(res):.1e}]', max(res) < 1e-8)
        else:
            report(f'B1 control a_{n}, s=+1: rho(B) has dim {A.shape[0]} and does not contain rho(kappa) '
                   f'[res {res[0]:.2f}]', res[0] > 1e-3)

# ------------------------------------------------------------------ B5
def blk(x, th, h):
    return mp.sinh(th / 2 + 1j * mp.pi * x / (2 * h)) / mp.sinh(th / 2 - 1j * mp.pi * x / (2 * h))

worst_fix, worst_print_C0 = 0, mp.inf
for h in (3, 4, 5, 6):
    for a in range(1, h):
        for C in (-1, 0, 1):
            for th in (mp.mpf('0.3'), mp.mpc('0.7', '0.2')):
                lhs = (mp.sinh(th) - 1j * C * mp.sin(mp.pi * a / h)) / (mp.sinh(th) + 1j * C * mp.sin(mp.pi * a / h))
                fixed = (-blk(a, th, h) * blk(h - a, th, h)) ** (-C)
                printed = -(blk(a, th, h) * blk(h - a, th, h)) ** (-C)
                worst_fix = max(worst_fix, abs(lhs - fixed))
                if C == 0:
                    worst_print_C0 = min(worst_print_C0, abs(lhs - printed))
report(f'B5 K_cl = [-(a)(h-a)]^-C for C = -1, 0, 1, h = 3..6 [{mp.nstr(worst_fix, 2)}]; printed '
       f'-[(a)(h-a)]^-C misses C = 0 by {mp.nstr(worst_print_C0, 2)}', worst_fix < 1e-30 and worst_print_C0 > 1)

# ------------------------------------------------------------------ B6
ok6 = True
for lam in (mp.sqrt(2) / 2, mp.sqrt(2), mp.e - mp.mpf('0.3')):          # one below, two inside (1, 3)
    qq = -mp.exp(-1j * mp.pi * lam)
    prod = (1 - qq) * (1 - 1 / qq)
    ok6 &= abs(prod - 4 * mp.cos(mp.pi * lam / 2) ** 2) < 1e-30
    branch = 2 * mp.cos(mp.pi * lam / 2)
    principal = mp.sqrt(prod)
    # Neumann point from the UV-IR map at mu = 0: eps = -cos((lam+1) pi/2)/sin(pi lam)
    eps_N = -mp.cos((lam + 1) * mp.pi / 2) / mp.sin(mp.pi * lam)
    ok6 &= abs(eps_N - 1 / branch) < 1e-30
    # GZ dictionary at xi_B = 0: k = 1/(eps sin pi lam) = 1/sin(pi lam/2) needs the branch 2cos
    ok6 &= abs(1 / ((1 / branch) * mp.sin(mp.pi * lam)) - 1 / mp.sin(mp.pi * lam / 2)) < 1e-30
    if 1 < lam < 3:
        ok6 &= abs(principal + branch) < 1e-30            # principal root is -2cos there
    else:
        ok6 &= abs(principal - branch) < 1e-30
report('B6 (1-q)(1-1/q) = 4cos^2(pi lam/2); Neumann eps = 1/(2cos(pi lam/2)) (UV-IR at mu=0 and GZ k); '
       'the principal root has the other sign for 1 < lam < 3', ok6)

# ------------------------------------------------------------------ B8
def blkI(yv, mu, T):
    return mp.sin(mp.pi * (mu + yv) / (2 * T)) / mp.sin(mp.pi * (mu - yv) / (2 * T))

om = mp.sqrt(2) + mp.mpf(1) / 7
mus = (mp.mpc('0.19', '0.13'), mp.mpc('-0.41', '0.35'))
res = {}
for n in range(1, 7):
    h = n + 1; T = h * om / 2
    def cond(sig):
        return max(abs(sig(mu) / mp.fprod(sig(mu + T - k * om) for k in range(1, n + 1)) - 1) for mu in mus)
    for name, x in (('w/2', om / 2), ('(w+1)/2', (om + 1) / 2), ('rand', mp.mpf('0.2713'))):
        P = lambda mu, x=x: blkI(T / 2 - x, mu, T) * blkI(T / 2 + x, mu, T)
        res[(n, name, '+')] = cond(P)
        res[(n, name, '-')] = cond(lambda mu: -P(mu))
    res[(n, 'sigma_c', 'ctrl')] = max(cond(lambda mu, c=c: -blkI(c * om / 2, mu, T) * blkI(T - c * om / 2, mu, T))
                                      for c in range(1, n + 1))
odd_ok = all(res[(n, nm, '+')] < 1e-25 for n in (1, 3, 5) for nm in ('w/2', '(w+1)/2', 'rand'))
even_fail = all(min(res[(n, nm, '+')], res[(n, nm, '-')]) > 1e-3 for n in (2, 4, 6) for nm in ('w/2', '(w+1)/2', 'rand'))
ctrl = all(res[(n, 'sigma_c', 'ctrl')] < 1e-25 for n in range(1, 7))
report('B8 soliton-bootstrap condition sigma(mu) = prod_k sigma(mu + T - k omega): every P_x (x = w/2, (w+1)/2, '
       'random) satisfies it for n = 1, 3, 5', odd_ok)
report('B8 for n = 2, 4, 6 neither P_x nor -P_x satisfies it (x = w/2, (w+1)/2, random) '
       f'[min defect {mp.nstr(min(min(res[(n, nm, "+")], res[(n, nm, "-")]) for n in (2, 4, 6) for nm in ("w/2", "(w+1)/2", "rand")), 2)}]',
       even_fail)
report('B8 control: DG sigma_c, c = 1..n, satisfy it for n = 1..6', ctrl)

