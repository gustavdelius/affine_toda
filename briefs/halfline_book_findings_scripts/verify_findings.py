ok11 = True
for lam in (mp.mpf('1.7'), mp.sqrt(5) + mp.mpf('0.1'), mp.mpf('4.3'), mp.sqrt(2) * 5):
    f = lambda m: -mp.cos((lam + 1) * mp.acos(m)) / mp.sin(mp.pi * lam)
    grid = [mp.mpf(k) / 4000 for k in range(1, 4000)]
    vals = [f(m) for m in grid]
    zeros = [mp.findroot(f, (grid[k], grid[k + 1]), solver='anderson') for k in range(len(grid) - 1)
             if mp.sign(vals[k]) != mp.sign(vals[k + 1])]
    pred = [mp.cos((2 * k + 1) * mp.pi / (2 * (lam + 1))) for k in range(0, 100) if 2 * k + 1 < lam + 1]
    ok11 &= len(zeros) == len(pred) and all(abs(z - p) < 1e-20 for z, p in zip(sorted(zeros), sorted(pred)))
    ok11 &= abs(max(zeros) - mp.cos(mp.pi / (2 * (lam + 1)))) < 1e-20
    print(f'   lam = {mp.nstr(lam, 4)}: zeros of eps on 0 < mu < 1: {[mp.nstr(z, 6) for z in sorted(zeros)]}')
report('B11 on phi_0 = 0, 0 < mu~/mu~crit < 1: eps-hat vanishes at cos((2k+1) pi/(2(lam+1))), 0 <= k < lam/2; '
       'one zero for lam < 2, several for lam > 2; cos(pi/(2(lam+1))) is the largest', ok11)

