"""Integration check (ch. 42, items 1, 2): exact obstructions, limits theta_d -> +-inf, the second module rho~.

Written from the chapter's definitions (sec-jump-coideal, eq-dbd-coproduct, conventions brief Sec. 6, 12):
 V(y): e_1 = y E+, f_1 = E-/y, k_1 = diag(q, 1/q), e_0 = y E-, f_0 = E+/y, k_0 = k_1^-1   (E+ : v_- -> v_+).
 The doubled-boundary equation for a generator x is  L(y) X_V(y) = X_V'(y) L(y),  L = P T, where the reflected copy
 at -theta carries pi_y as well; X_V, X_V' are the actions of (sigma (x) chi) Delta_A(x) on V (x) W and V' (x) W.
 Type I_-: L(v+ n) = A_n v+ n + C_n v- (n+1), L(v- n) = B_n v+ (n-1) + D_n v- n,
   A = q^-n, D = q^(n+s), C = -i (y/yd) q^-n, B = -i (y/yd) q^(n+s);
 Type I_+: A = q^n, D = q^(-n-s), C = i q^(-1-s) (yd/y) q^-n, B = i q^-1 (yd/y) q^n.
Part A uses noncommutative symbols for every operator on W (arbitrary operators); part B exact shift operators.
"""
import sympy as sp

y, q, t = sp.symbols('y q t', nonzero=True)
ok_all = True


def say(label, ok):
    global ok_all
    ok_all &= bool(ok)
    print(('PASS ' if ok else 'FAIL ') + label)


# ------------------------------------------------------------------ Part A: arbitrary operators on W
A_, D0, Bo, Co, Y, K, Z = sp.symbols('A D0 Bo Co Y kappa Z', commutative=False)
one = sp.Integer(1)
Ep = sp.Matrix([[0, one], [0, 0]])          # E+ (x) 1   (v_- -> v_+)
Em = sp.Matrix([[0, 0], [one, 0]])
I2 = sp.eye(2)


def kq(p):                                  # pi(k_1)^p (x) op as a block matrix acting by the scalar on V
    return lambda op: sp.Matrix([[q**p*op, 0], [0, q**-p*op]])


def tens(Vm, op):                           # (2x2 numeric) (x) op
    return Vm.applyfunc(lambda c: c*op)


Dm = sp.Matrix([[A_, 0], [0, D0]])
Om = sp.Matrix([[0, Bo], [Co, 0]])


def coeffs(M, var, powers):
    M = M.applyfunc(sp.expand)
    return {p: M.applyfunc(lambda e: e.coeff(var, p)) for p in powers}


Lm = Dm + y*Om                              # type I_-: L = D + y O
Lp = Dm + Om/y                              # type I_+: L = D + y^-1 O
# I_- , untwisted e_1 with torus factor t:  L (y E+ (x) 1 + k (x) Y) = (1 (x) Y + t y E+ (x) kappa) L
eq = Lm*(y*Ep + kq(1)(Y)) - (tens(I2, Y) + t*y*tens(Ep, K))*Lm
c2 = coeffs(eq, y, [2])[2]
say(f'I_- e/id: y^2 coefficient = {list(c2)}; its (v-,v-) block is Co alone, so no operators Y, kappa solve it',
    c2[1, 1] == Co and c2[0, 1] == 0 and c2[1, 0] == 0)
# I_- , tau-twisted f_1 (psi(f_1) = f_0/t):  L (E-/y (x) kappa + 1 (x) Y) = (pi(k_0^-1) (x) Y + t^-1 E+/y (x) 1) L
eq = Lm*(Em/y*K + tens(I2, Y)) - (kq(1)(Y) + Ep/(t*y))*Lm
cm1 = coeffs(eq*y, y, [0])[0]               # coefficient of y^-1
say(f'I_- f/tau: y^-1 coefficient = {list(cm1)}; its (v+,v-) block is -D0/t alone',
    sp.simplify(cm1[0, 1] + D0/t) == 0)
# I_+ , untwisted f_1:  y^-2 coefficient
eq = Lp*(Em/y*K + tens(I2, Y)) - (kq(1)(Y) + Em/(t*y))*Lp
cm2 = coeffs(sp.expand(eq*y**2), y, [0])[0]
say(f'I_+ f/id: y^-2 coefficient = {list(cm2)}; its (v-,v-) block is -Bo/t alone', sp.simplify(cm2[1, 1] + Bo/t) == 0)
# I_+ , tau-twisted e_1 (psi(e_1) = t e_0):  y^1 coefficient
eq = Lp*(y*Ep + kq(1)(Y)) - (tens(I2, Y) + t*y*tens(Em, K))*Lp
c1 = coeffs(eq, y, [1])[1]
say(f'I_+ e/tau: y^1 coefficient = {list(c1)}; its (v+,v-) block is A alone', c1[0, 1] == A_)
# prp-diagonal-borel (4): e_1 (x) 1 for I_- and 1 (x) f_0 for I_+, arbitrary Z
eq = Lm*(y*Ep + kq(1)(Z)) - tens(I2, Z)*Lm
c2 = coeffs(eq, y, [2])[2]
say(f'(4) I_-: e_1 (x) 1 has y^2 coefficient {list(c2)}: (v-,v-) block Co', c2[1, 1] == Co)
eq = Lp*tens(I2, Z) - (kq(1)(Z) + Ep/y)*Lp     # 1 (x) f_0: V: 1 (x) Z;  V': pi(k_0^-1) (x) Z + pi(f_0) (x) 1
cm2 = coeffs(sp.expand(eq*y**2), y, [0])[0]
say(f'(4) I_+: 1 (x) f_0 has y^-2 coefficient {list(cm2)}: (v+,v+) block -Co', cm2[0, 0] == -Co)

# the algebra step of (4): e_1 (x) 1 and 1 (x) f_0 lie in the algebra generated by the two halves (in pi (x) pi)
import numpy as np
qn = np.exp(0.71j)
E = np.array([[0, 1], [0, 0]]); F = E.T; Kk = np.diag([qn, 1/qn])
y1, y2 = 1.3 + 0.2j, 0.7 - 0.4j
e1 = lambda yy: yy*E; e0 = lambda yy: yy*F; f1 = lambda yy: F/yy; f0 = lambda yy: E/yy
G = np.kron(Kk, Kk)
x_m = np.kron(e1(y1), np.eye(2)) + np.kron(Kk, e0(y2))                       # (1 (x) tau)Delta(e_1)
x_p = np.kron(f1(y1), Kk) + np.kron(np.eye(2), f0(y2))                       # (1 (x) tau)Delta(f_1), k_0^-1 = K
lin = lambda x_: (G @ x_ @ np.linalg.inv(G) - x_/qn**2)/(qn**2 - qn**-2)
say('e_1 (x) 1 = (G x G^-1 - q^-2 x)/(q^2 - q^-2), x = e_1 (x) 1 + k_1 (x) e_0;  1 (x) f_0 likewise from '
    'x = f_1 (x) k_0^-1 + 1 (x) f_0  (G = k_1 (x) k_1, in pi (x) pi)',
    np.allclose(lin(x_m), np.kron(e1(y1), np.eye(2))) and np.allclose(lin(x_p), np.kron(np.eye(2), f0(y2))))

# ------------------------------------------------------------------ Part B: exact shift operators on W
n, s, yd = sp.symbols('n s y_d')


class S:
    """operator |n> -> sum_m c_m(n) |n+m>"""
    def __init__(self, d=None):
        self.d = {k: sp.sympify(v) for k, v in (d or {}).items()}

    def __add__(self, o):
        out = dict(self.d)
        for k, v in o.d.items():
            out[k] = out.get(k, 0) + v
        return S(out)

    def __sub__(self, o):
        return self + o*(-1)

    def __mul__(self, o):                    # composition self o other, or scalar
        if not isinstance(o, S):
            return S({k: v*o for k, v in self.d.items()})
        out = {}
        for m, cm in o.d.items():
            for m2, c2 in self.d.items():
                out[m + m2] = out.get(m + m2, 0) + cm*c2.subs(n, n + m)
        return S(out)

    __rmul__ = lambda self, c: S({k: v*c for k, v in self.d.items()})

    def zero(self):
        return all(sp.simplify(v) == 0 for v in self.d.values())


ONE = S({0: 1})
Zr = S({})


def bmul(P, R):                              # 2x2 block matrices of S
    return [[P[i][0]*R[0][j] + P[i][1]*R[1][j] for j in range(2)] for i in range(2)]


def badd(P, R, c=1):
    return [[P[i][j] + R[i][j]*c for j in range(2)] for i in range(2)]


def bzero(P):
    return all(P[i][j].zero() for i in range(2) for j in range(2))


def Vop(M, op=ONE):                          # numeric 2x2 matrix on V (x) operator on W
    return [[op*sp.sympify(M[i][j]) if M[i][j] != 0 else Zr for j in range(2)] for i in range(2)]


EP, EM, KQ, KQi, I = [[0, 1], [0, 0]], [[0, 0], [1, 0]], [[q, 0], [0, 1/q]], [[1/q, 0], [0, q]], [[1, 0], [0, 1]]


def L_minus(yy):
    return [[S({0: q**-n}), S({-1: -sp.I*(yy/yd)*q**(n + s)})], [S({1: -sp.I*(yy/yd)*q**-n}), S({0: q**(n + s)})]]


def L_plus(yy):
    return [[S({0: q**n}), S({-1: sp.I/q*(yd/yy)*q**n})], [S({1: sp.I*q**(-1 - s)*(yd/yy)*q**-n}), S({0: q**(-n - s)})]]


# second module rho~ (eq-dbd-second-module), type I_-
a, b = sp.I*yd*q**-s/(q**2 - 1), sp.I*yd*q**s/(q**2 - 1)
rt = {('e', 1): S({1: a*q**(-2*n)}), ('k', 1): S({2: q**(-2*n - 2 - s)}),
      ('e', 0): S({-1: b*q**(2*n)}), ('k', 0): S({-2: q**(2*n - 2 + s)})}
rels = [rt[('k', 0)]*rt[('k', 1)] - ONE, rt[('k', 1)]*rt[('k', 0)] - ONE,
        rt[('k', 1)]*rt[('e', 1)] - rt[('e', 1)]*rt[('k', 1)]*q**2, rt[('k', 1)]*rt[('e', 0)] - rt[('e', 0)]*rt[('k', 1)]*q**-2,
        rt[('k', 0)]*rt[('e', 0)] - rt[('e', 0)]*rt[('k', 0)]*q**2, rt[('k', 0)]*rt[('e', 1)] - rt[('e', 1)]*rt[('k', 0)]*q**-2,
        rt[('e', 1)]*rt[('e', 0)] - S({0: a*b*q**2}), rt[('e', 0)]*rt[('e', 1)] - S({0: a*b*q**2})]
say('rho~: k_0 k_1 = k_1 k_0 = 1, k e k^-1 = q^(+-2) e, e_1 e_0 = e_0 e_1 = a b q^2 (central; so q-Serre), all n',
    all(r_.zero() for r_ in rels))
# intertwining for all four generators of (1 (x) tau)Delta(U_q(b^+)), all n and all y
Lm_ = L_minus(y)
piV = {('e', 1): [[0, y], [0, 0]], ('e', 0): [[0, 0], [y, 0]], ('k', 1): KQ, ('k', 0): KQi}
ok_int = True
for j in (1, 0):
    jt = 1 - j
    XV = badd(Vop(piV[('e', j)]), Vop(piV[('k', j)], rt[('e', j)]))
    XVp = badd(Vop(I, rt[('e', j)]), Vop(piV[('e', jt)], rt[('k', j)]))
    ok_int &= bzero(badd(bmul(Lm_, XV), bmul(XVp, Lm_), -1))
    XV = Vop(piV[('k', j)], rt[('k', j)])
    XVp = Vop(piV[('k', jt)], rt[('k', j)])
    ok_int &= bzero(badd(bmul(Lm_, XV), bmul(XVp, Lm_), -1))
say('rho~: L intertwines (sigma (x) chi)Delta_A of (1 (x) tau)Delta(e_j), (1 (x) tau)Delta(k_j), j = 0, 1, exactly', ok_int)
# the free constant: Y_n = a q^-2n + c solves the e_1 equation for every c, Cartan covariance forces c = 0
c_ = sp.symbols('c')
Yc = S({1: a*q**(-2*n) + c_})
XV = badd(Vop(piV[('e', 1)]), Vop(KQ, Yc)); XVp = badd(Vop(I, Yc), Vop(piV[('e', 0)], rt[('k', 1)]))
cov = rt[('k', 1)]*Yc - Yc*rt[('k', 1)]*q**2
say('e_1 equation leaves an additive constant c in Y_n; k_1 Y k_1^-1 = q^2 Y holds iff c (1 - q^4) = 0',
    bzero(badd(bmul(Lm_, XV), bmul(XVp, Lm_), -1)) and sp.simplify(cov.d[3] - c_*q**(-2*n - 4 - s)*(1 - q**4)) == 0)
# the q^4 relation of exr-dbd-mixed-twist
rk1 = S({0: q**(2*n + s)})
say('rho(k_1) rho~(k_1) = q^4 rho~(k_1) rho(k_1)', (rk1*rt[('k', 1)] - rt[('k', 1)]*rk1*q**4).zero())

# ------------------------------------------------------------------ limits theta_d -> +-inf
# The matrices are L = Ddiag + (y/yd) O (I_-) and L = Ddiag + (yd/y) O (I_+): the diagonal limit is theta_d -> +inf for
# I_- and theta_d -> -inf for I_+.
Lm_d = [[S({0: q**-n}), Zr], [Zr, S({0: q**(n + s)})]]
Lp_d = [[S({0: q**n}), Zr], [Zr, S({0: q**(-n - s)})]]
say('I_-: off-diagonal entries are exactly (y/y_d) times theta-independent operators; I_+: (y_d/y) times; so the '
    'diagonal limit is theta_d -> +inf for I_- and theta_d -> -inf for I_+',
    all(sp.simplify(sp.diff(Lm_[i][j].d[k], yd)*yd + Lm_[i][j].d[k]) == 0 for i, j in ((0, 1), (1, 0)) for k in Lm_[i][j].d)
    and all(sp.simplify(sp.diff(L_plus(y)[i][j].d[k], yd)*yd - L_plus(y)[i][j].d[k]) == 0
            for i, j in ((0, 1), (1, 0)) for k in L_plus(y)[i][j].d))


def forced_kappas(Ld, untw=True):
    """diagonal limit, untwisted e_1 and f_1 with torus t: the y^1 coefficient of the e-equation forces
    kappa_e = chi(Delta k_1) = t^-1 A D^-1 (block (v+, v-): A = t kappa D) and the y^-1 coefficient of the
    f-equation forces kappa_f = chi(Delta k_1^-1) = t^-1 D^-1 A (block (v-, v+): D kappa_f = t^-1 A)."""
    Aop, Dop = Ld[0][0], Ld[1][1]
    Dinv = S({0: 1/Dop.d[0]})
    return Aop*Dinv*(1/t), Dinv*Aop*(1/t)


for name, Ld, expect in (('I_-, theta_d -> +inf', Lm_d, t**-2*q**(-4*n - 2*s)), ('I_+, theta_d -> -inf', Lp_d, t**-2*q**(4*n + 2*s))):
    ke, kf = forced_kappas(Ld)
    # verify that kappa_e, kappa_f do solve their own y-coefficient equations
    Kb = lambda op: Vop(EP, op)
    eq_e = badd(bmul(Ld, Vop(EP)), bmul(Vop(EP, ke), Ld), -t)
    eq_f = badd(bmul(Ld, Vop(EM, kf)), bmul(Vop(EM), Ld), -1/t)
    prod = (ke*kf).d[0]
    say(f'{name}: the e_1 and f_1 equations force chi(Delta k_1) = {sp.simplify(ke.d[0])}, chi(Delta k_1^-1) = '
        f'{sp.simplify(kf.d[0])} (the same operator); product {sp.simplify(prod)} != 1 for generic q',
        bzero(eq_e) and bzero(eq_f) and sp.simplify(prod - expect) == 0)
# sector-wise: on C|n> the diagonal limit is the twist line t_n = A_n/D_n with trivial module (kappa = 1)
say('on each charge sector C|n> the I_- diagonal limit is the twist line with t_1 = 1/t_0 = q^(-2n-s) (kappa = 1)',
    sp.simplify(forced_kappas(Lm_d)[0].d[0].subs(t, q**(-2*n - s)) - 1) == 0)
# off-diagonal limit (I_-, theta_d -> -inf), tau-twisted e_1 and f_1: kappa = t^-1 C B^-1, kappa' = t^-1 B^-1 C
Bm_ = S({-1: -sp.I*q**(n + s)}); Cm_ = S({1: -sp.I*q**-n})
Binv = S({1: sp.I*q**(-(n + 1) - s)})        # B|n+1> = -i q^(n+1+s) |n>  =>  B^-1|n> = (i q^-(n+1+s)) |n+1>
say('B^-1 is the inverse of B', ((Bm_*Binv) - ONE).zero() and ((Binv*Bm_) - ONE).zero())
Od = [[Zr, Bm_], [Cm_, Zr]]
ke, kf = Cm_*Binv*(1/t), Binv*Cm_*(1/t)
eq_e = badd(bmul(Od, Vop(EP)), bmul(Vop(EM, ke), Od), -t)       # y^1: O (E+ (x) 1) = t (E- (x) kappa) O
eq_f = badd(bmul(Od, Vop(EM, kf)), bmul(Vop(EP), Od), -1/t)     # y^-1: O (E- (x) kappa') = t^-1 (E+ (x) 1) O
say(f'I_-, theta_d -> -inf, tau-twisted: chi(k_1 (x) k_0) = {list(ke.d.items())}, chi(k_1^-1 (x) k_0^-1) = '
    f'{list(kf.d.items())}: both raise n by 2, so their product raises it by 4 and is not 1',
    bzero(eq_e) and bzero(eq_f) and set(ke.d) == {2} and set(kf.d) == {2} and set((ke*kf).d) == {4})
print('ALL PASS' if ok_all else 'SOME FAIL')
